def line(d, c=O, w=3):
    return f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>'


def fig(x, y, suit, legs, arms, hair="#5D4037", style="short", rot=0, legc=SKIN, armc=SKIN, hr=11, k=0.42, extra="", sc=1.0):
    """человечек: (0,0) — таз, плечи (0,-22), голова (0,-36); legs/arms — пути относительно таза"""
    b = "".join(limb(d, legc, 6) for d in legs)
    b += path("M-8 -24 Q0 -27 8 -24 L9 0 H-9Z", suit, 2.6)
    b += "".join(limb(d, armc, 5) for d in arms)
    b += extra
    b += G(0, -36, head(0, 0, hair, hr, k, style))
    return G(x, y, b, rot, sc)


def mat(y, c, c2=None):
    return path(f"M-6 {y} H134 V140 H-6Z", c, 2.6) + (line(f"M-6 {y+8} H134", c2, 2) if c2 else "")


def ribbon(d, c="#FF4F8B", w=4):
    return line(d, c, w)


def stick(x1, y1, x2, y2, c="#FFFFFF"):
    return line(f"M{x1} {y1} L{x2} {y2}", O, 5) + line(f"M{x1} {y1} L{x2} {y2}", c, 3)


def hoopr(cx, cy, r, c="#FFC107", w=6):
    return (f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{O}" stroke-width="{w+3}"/>'
            f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="{c}" stroke-width="{w}"/>')


def rgball(cx, cy, r, c, fc=True):
    return circ(cx, cy, r, c) + ell(cx - r * 0.35, cy - r * 0.4, r * 0.3, r * 0.18, "#FFFFFF", 0).replace('fill="#FFFFFF"', 'fill="#FFFFFF" opacity=".55"') + (face(cx, cy + r * 0.15, d=r * 0.3, k=r / 30) if fc else "")


def glove(x, y, c, rot=0, sc=1.0, fc=False):
    g = path("M-10 -12 Q-12 -22 0 -22 Q14 -22 13 -6 Q13 8 2 10 H-8 Q-13 4 -10 -12Z", c, 2.6)
    g += path("M-10 -10 Q-18 -8 -15 2 Q-12 6 -8 2", c, 2.4) + rect(-9, 9, 13, 8, "#FFFFFF", 2, 2.4)
    if fc:
        g += face(2, -8, d=4, k=0.4)
    return G(x, y, g, rot, sc)


