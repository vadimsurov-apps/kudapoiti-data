def tramp(cx, cy, rx, mat, frame="#37474F", legs=True):
    out = ""
    if legs:
        out += path(f"M{cx-rx+8} {cy+4} L{cx-rx+2} {cy+26} M{cx+rx-8} {cy+4} L{cx+rx-2} {cy+26} "
                    f"M{cx-rx*.35} {cy+9} L{cx-rx*.38} {cy+30} M{cx+rx*.35} {cy+9} L{cx+rx*.38} {cy+30}", "none", 3.4)
    return out + ell(cx, cy, rx, rx * .25, frame, 2.8) + ell(cx, cy - 1, rx - 6, rx * .25 - 3, mat, 2.2)


def ball(x, y, r=7, c=YEL):
    return (circ(x, y, r, c, 2.2)
            + path(f"M{x-r*.85} {y-r*.35} Q{x} {y+r*.4} {x+r*.85} {y-r*.35}", "none", 1.5).replace(O, "#ffffff", 1))


def head(x, y, r, hair, k=0.42):
    return circ(x, y, r, SKIN, 2.4) + hair + face(x, y + 1, r * .38, k)


def puffs(pts, c="#FFFFFF"):
    return "".join(circ(x, y, r, c, 2) for x, y, r in pts)


