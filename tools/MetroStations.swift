    /// Ищет станцию по названию: «Шелепиха», «м. Шелепиха», «метро Шелепиха», «шелепиха мцк».
    static func find(_ raw: String) -> (name: String, location: CLLocation)? {
        let key = normalize(raw)
        guard !key.isEmpty else { return nil }
        let resolved = aliases[key] ?? key
        if let c = coords[resolved] { return (c.0, CLLocation(latitude: c.1, longitude: c.2)) }
        // Неполное название: «проспект мира» найдёт «проспект мира», «бауман» — «бауманская»
        let matches = coords.keys.filter { $0.hasPrefix(resolved) }.sorted()
        if let first = matches.first, let c = coords[first] {
            return (c.0, CLLocation(latitude: c.1, longitude: c.2))
        }
        return nil
    }

    static func normalize(_ s: String) -> String {
        var t = s.lowercased().replacingOccurrences(of: "ё", with: "е")
        for junk in ["«", "»", "\"", "станция", "метро", "мцк", "мцд", "бкл", "м."] {
            t = t.replacingOccurrences(of: junk, with: " ")
        }
        return t.split(whereSeparator: { $0.isWhitespace }).joined(separator: " ")
    }

