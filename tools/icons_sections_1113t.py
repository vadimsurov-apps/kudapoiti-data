def star(cx, cy, r, c, sw=2.6, inner=0.48):
    import math
    pts = []
    for i in range(10):
        a = -math.pi / 2 + i * math.pi / 5
        rr = r if i % 2 == 0 else r * inner
        pts.append(f"{cx + rr * math.cos(a):.1f} {cy + rr * math.sin(a):.1f}")
    return path("M" + " L".join(pts) + "Z", c, sw)


