def star(x, y, r, c, sw=2.4):
    import math
    pts = []
    for i in range(10):
        a = math.pi / 2 + i * math.pi / 5
        rr = r if i % 2 == 0 else r * 0.45
        pts.append(f"{x + rr * math.cos(a):.1f},{y - rr * math.sin(a):.1f}")
    return f'<polygon points="{" ".join(pts)}" fill="{c}" {s(f"stroke-width={chr(34)}{sw}{chr(34)}")}/>'


