def main(ids):
    lines = open(os.path.join(OUT, "subjects.txt"), encoding="utf-8").read().split("\n")
    lines = [l for l in lines if l.split(" — ")[0] not in ids]
    for pid in ids:
        open(os.path.join(OUT, f"{pid}.svg"), "w").write(ICONS[pid])
        lines.append(SUBJ[pid])
    open(os.path.join(OUT, "subjects.txt"), "w", encoding="utf-8").write("\n".join(l for l in lines if l) + "\n")
    print("иконок:", len(ids))


if __name__ == "__main__":
    main(sys.argv[1:] or list(ICONS))
