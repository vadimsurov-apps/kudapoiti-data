def row(d):
    pid, name, addr, lat, lon, site, plus, room, check, hours, acc = d
    minus = f"Детская — по Яндекс Картам: {room}; часы работы детской и аниматоров уточняйте по телефону"
    note = f"средний чек ~{check} ₽" if check else "средний чек — уточняйте"
    r = P(pid, name, "кафе", metro(lat, lon), addr, lat, lon, 0, 12, 60, 150, "спокойно", "творчество", None,
          note, hours, "да", plus, minus, adult=3, src=YM + (f"; {site}" if site else ""), acc=acc,
          booking="желательна", loud="частично", food="да", stroller="да")
    r["Сайт"] = site
    r["Категории"] = "food"
    r["Проверено (дата)"] = DAY
    return r


