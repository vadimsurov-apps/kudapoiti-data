"""Свод договорённостей для GPT (Вадим 11.11: «он должен знать всё, о чём мы договорились, чтобы не делать по-своему»).
Собирает gpt/RULES.md из CLAUDE.md — разделы о качестве карточек, уроки разборов с Вадимом, правила точек и формат
«Как найти». Запускается сборкой, поэтому GPT всегда читает актуальную версию тех же правил, что и наши роботы."""
import os, re
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
WANT = ("Качество карточек", "Уроки разборов с Вадимом", "Только подтверждённое на карте", "Категории фильтра")


def main():
    import sys
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    from rules_all import full
    md = full()   # ядро CLAUDE.md + rules/*.md (свод разнесён по файлам 13.11)
    secs = re.split(r"(?m)^## ", md)
    out = ["# Правила данных «Куда пойти с детьми» — для независимого проверяющего (ChatGPT)",
           "Это выдержка из главного свода правил (CLAUDE.md), собирается автоматически. Всё, что здесь сказано, обязательно и для тебя:",
           "ничего не выдумывать, только из источника; те же форматы полей; те же уроки разборов с владельцем (Вадимом).",
           "Отличие от наших роботов: ты ничего не правишь в таблицах сам — только пишешь отчёт по формату gpt/README.md.", ""]
    for s in secs[1:]:
        title = s.split("\n", 1)[0]
        if any(title.startswith(w) for w in WANT):
            out.append("## " + s.strip() + "\n")
    m = re.search(r"Формат «Как найти».*?(?=\nПравила:)", md, re.S)
    if m:
        out.append("## Формат поля «Как найти»\n" + m.group(0).strip() + "\n")
    open(os.path.join(ROOT, "gpt", "RULES.md"), "w", encoding="utf-8").write("\n".join(out))
    print("gpt/RULES.md:", len("\n".join(out)), "символов")


if __name__ == "__main__":
    main()
