# --- общий человечек для сцен ниже (рисуется вручную в каждой сцене своими цветами и позой) ---
def head(x, y, r, skin="#FFD7B5", hair=None, hc="#5B3A29", k=0.5):
    out = circ(x, y, r, skin, 2.8)
    if hair:
        out += path(hair, hc, 1.8)
    return out + eye(x - r * 0.38, y + 1, k) + eye(x + r * 0.38, y + 1, k) + mouth(x, y + r * 0.5, r * 0.25, 1.5)


