    r["Категории"] = cats
    r["Проверено (дата)"] = DAY
    if changing:
        r["Пеленальный стол"] = changing
    if how:
        r["Как найти"] = how
    ROWS.append(r)
    f = {"address": addr, "age_min": a0, "age_max": a1}
    if osm:
        f["point"] = {"lat": lat, "lon": lon, "level": "объект", "how": f"OSM {osm}"}
    if phone:
        f["phone"] = phone
    if site:
        f["url"] = site
    if hours:
        f["hours"] = hours
    if child is not None:
        f["price_child"] = child
    if adult not in (None, ""):
        f["price_adult"] = adult
    if note:
        f["free_note"] = note
    VER[pid] = {"fields": f, "src": src}


