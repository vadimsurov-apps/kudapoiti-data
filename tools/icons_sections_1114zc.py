# ---------------- IBASKET (10 залов) и «Философия бокса» — у каждого свой герой, своя сцена и палитра ----------------
def hoopb(x, y, w=30, bc="#FFFFFF"):
    """щит с кольцом и сеткой; (x,y) — центр щита"""
