def vball(x, y, r, a="#FFFFFF", b="#2F6FE0", c="#FFD23C", face=True, k=1.0):
    """волейбольный мяч: три цветные панели-дуги"""
    g = (circ(0, 0, r, a, 3.0)
         + path(f"M{-r*0.98} {-r*0.18} Q{-r*0.2} {-r*0.55} {r*0.2} {-r*0.97} Q{r*0.55} {-r*0.55} {r*0.15} {-r*0.05} Q{-r*0.45} {-r*0.05} {-r*0.98} {-r*0.18}Z", b, 2.2)
         + path(f"M{r*0.15} {-r*0.05} Q{r*0.6} {r*0.2} {r*0.96} {-r*0.28} Q{r*1.0} {r*0.45} {r*0.55} {r*0.83} Q{r*0.5} {r*0.3} {r*0.15} {-r*0.05}Z", c, 2.2)
         + path(f"M{r*0.15} {-r*0.05} Q{-r*0.1} {r*0.5} {-r*0.55} {r*0.83}", "none", 2.2))
    if face:
        g += eye(-r * 0.32, r * 0.22, 0.7 * r / 22) + eye(r * 0.12, r * 0.22, 0.7 * r / 22) + mouth(-r * 0.1, r * 0.48, 3.2 * r / 22, 2.0) \
            + blush(-r * 0.55, r * 0.45) + blush(r * 0.35, r * 0.45)
    return G(x, y, g, 0, k)


def net(y0, y1, x0=-4, x1=132, c="#FFFFFF"):
    rows = "".join(line(f"M{x0} {yy} H{x1}", c, 1.2) for yy in range(y0 + 6, y1, 6))
    cols = "".join(line(f"M{xx} {y0} V{y1}", c, 1.2) for xx in range(x0 + 6, x1, 6))
    return rows + cols + rect(x0, y0 - 3, x1 - x0, 5, "#FFFFFF", 1, 2.2)


