from openpyxl.styles import Font, Alignment, Border, Side
from add_batch14 import base, metro, MET, SRC

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
CAND = {x["osm"]: x for x in json.load(open(os.path.join(ROOT, "auto", "candidates.json")))["candidates"]}
ST = {n.lower().replace("ё", "е"): (a, b) for n, a, b in MET}
SRC_OK = "сайт места (проверено 2026-11-05)"
SRC_OSM = "OpenStreetMap; данные — с сайта места (проверено 2026-11-05)"
APPROX = "приблизительно, ±1 км (по станции метро)"
_used = {}


def where(osm=None, st=None, coords=None):
    """(lat, lon, metro, acc, src)"""
    if osm:
        x = CAND[osm]
        return x["lat"], x["lon"], metro(x["lat"], x["lon"]), "точно (OpenStreetMap)", SRC_OSM
    if coords:
        return coords[0], coords[1], metro(*coords), "точно (OpenStreetMap)", SRC_OSM
    a, b = ST[st.lower().replace("ё", "е")]
    k = _used.get(st, 0); _used[st] = k + 1        # разводим точки у одной станции, чтобы не слипались
    ang = k * 2.1
    a += 0.0012 * math.sin(ang) * (1 if k else 0); b += 0.002 * math.cos(ang) * (1 if k else 0)
    return round(a, 6), round(b, 6), st, APPROX, SRC_OK


