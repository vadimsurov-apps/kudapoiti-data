def line(d, c, sw):
    return path(d, "none", sw).replace(O, c, 1)


def tramp(cx, cy, rx, mat="#2E2A3E", frame="#3FA9F5", legs=True):
    """батут сбоку: рама-обод, тёмное полотно, ножки"""
    out = ""
    if legs:
        out += "".join(line(f"M{cx+dx} {cy+3} L{cx+dx*1.08} {cy+22}", O, 4) for dx in (-rx * .8, -rx * .3, rx * .3, rx * .8))
    out += ell(cx, cy, rx, rx * .26, frame, 3) + ell(cx, cy - 1, rx * .82, rx * .18, mat, 2)
    return out


def deck(cx, cy, w, c="#F2994A", rot=0, wheel="#FFE07A"):
    """скейтборд сбоку"""
    b = (path(f"M{-w/2} -3 Q{-w/2-7} -9 {-w/2-4} -1 Q{-w/2} 4 {-w/2+6} 4 H{w/2-6} Q{w/2} 4 {w/2+4} -1 "
              f"Q{w/2+7} -9 {w/2} -3Z", c, 2.8)
         + circ(-w / 2 + 9, 9, 5, wheel, 2.4) + circ(w / 2 - 9, 9, 5, wheel, 2.4))
    return G(cx, cy, b, rot, 1)


def tyre(x, y, r=10, c="#2E2A3E"):
    return circ(x, y, r, c, 2.6) + circ(x, y, r * .42, "#C9C4D6", 2)


