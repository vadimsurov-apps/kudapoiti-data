def grid(rows, x0, y0, k, cmap):
    out = ""
    for cy, row in enumerate(rows):
        for cx, ch in enumerate(row):
            if ch in cmap:
                out += f'<rect x="{x0 + cx * k}" y="{y0 + cy * k}" width="{k}" height="{k}" fill="{cmap[ch]}"/>'
    return out
