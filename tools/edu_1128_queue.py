"""Робот edu, 13.11 (восемнадцатый запуск): выдачи Яндекс Карт по районам → auto/fetch-queue.txt (ключи eu<N>-1128e).
На район: 2 запроса «Особым детям» + 2 по направлениям (сады, чтение, математика, ментальная арифметика, программирование, лего,
логопед, нейропсихолог, монтессори)."""
import json, os, urllib.parse
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
METRO = ["Хорошёво", "Щёлковская", "Щукинская", "Электрозаводская", "Юго-Восточная", "Юго-Западная", "Южная", "Ясенево", "Яхромская"]
TOWNS = ["Троицк", "Щербинка", "Коммунарка", "Московский", "Дедовск", "Павловский Посад"]
INC = ["занятия для детей с ОВЗ", "инклюзивный центр для детей", "адаптивная физкультура для детей",
       "занятия для детей с аутизмом", "сенсорная интеграция для детей", "коррекционный центр для детей", "АВА-терапия для детей"]
TH = ["частный детский сад", "скорочтение для детей", "математический кружок для детей", "ментальная арифметика",
      "программирование для детей", "лего конструирование для детей", "логопед для детей", "нейропсихолог для детей", "монтессори"]
Q = []
for i, a in enumerate(METRO + TOWNS):
    w = f"метро {a}" if a in METRO else a
    for t in (INC[(2 * i + 3) % 7], INC[(2 * i + 4) % 7], TH[(2 * i + 5) % 9], TH[(2 * i + 6) % 9]):
        Q.append(f"{t} {w}")
Q += ["иппотерапия для детей Подмосковье", "инклюзивная студия для детей Москва", "адаптивное плавание для детей с ОВЗ Москва",
      "занятия для детей с ДЦП Москва", "занятия для слабослышащих детей Москва", "робототехника для детей метро Ясенево",
      "программирование для детей метро Щукинская", "частный детский сад метро Юго-Западная"]
if __name__ == "__main__":
    urls = [f"https://yandex.ru/maps/1/moscow-and-moscow-oblast/?eu{n}=1128e&text=" + urllib.parse.quote(q) for n, q in enumerate(Q)]
    old = open(os.path.join(ROOT, "auto/fetch-queue.txt")).read()
    open(os.path.join(ROOT, "auto/fetch-queue.txt"), "w").write("\n".join(urls) + "\n" + old)
    json.dump(Q, open(os.path.join(ROOT, "tools/edu_1128_queries.json"), "w"), ensure_ascii=False, indent=0)
    print(len(urls))
