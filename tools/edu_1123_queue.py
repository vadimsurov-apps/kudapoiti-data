"""Робот edu, 12.11 (тринадцатый запуск): выдачи Яндекс Карт по районам → auto/fetch-queue.txt (ключи eu<N>-1123e).
На район: 2 запроса «Особым детям» + 2 по новым направлениям (сады, чтение, математика, ментальная арифметика, программирование, лего)."""
import json, os, urllib.parse
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
AREAS = ["Лубянка", "Лужники", "Новомосковская", "Октябрьская", "Ольховая", "Охотный ряд", "Парк культуры", "Петровский парк",
         "Петровско-Разумовская", "Печатники", "Пионерская", "Планерная", "Площадь Гагарина", "Площадь Ильича", "Полежаевская"]
INC = ["занятия для детей с ОВЗ", "инклюзивный центр для детей", "адаптивная физкультура для детей",
       "занятия для детей с аутизмом", "сенсорная интеграция для детей", "коррекционный центр для детей"]
TH = ["частный детский сад", "скорочтение для детей", "математический кружок для детей", "ментальная арифметика",
      "программирование для детей", "лего конструирование для детей", "обучение чтению детей", "школа программирования для детей"]
Q = []
for i, a in enumerate(AREAS):
    for t in (INC[(2 * i + 1) % 6], INC[(2 * i + 2) % 6], TH[(2 * i + 3) % 8], TH[(2 * i + 4) % 8]):
        Q.append(f"{t} метро {a}")
Q += ["иппотерапия для детей Москва", "адаптивное плавание для детей Москва", "инклюзивная творческая студия для детей Москва",
      "занятия для детей с синдромом Дауна Москва", "занятия для слабослышащих детей Москва", "инклюзивный центр для детей Химки",
      "инклюзивный центр для детей Люберцы", "инклюзивный центр для детей Красногорск", "занятия для детей с аутизмом Королёв"]
if __name__ == "__main__":
    urls = [f"https://yandex.ru/maps/1/moscow-and-moscow-oblast/?eu{n}=1123e&text=" + urllib.parse.quote(q) for n, q in enumerate(Q)]
    old = open(os.path.join(ROOT, "auto/fetch-queue.txt")).read()
    open(os.path.join(ROOT, "auto/fetch-queue.txt"), "w").write("\n".join(urls) + "\n" + old)
    json.dump(Q, open(os.path.join(ROOT, "tools/edu_1123_queries.json"), "w"), ensure_ascii=False, indent=0)
    print(len(urls))
