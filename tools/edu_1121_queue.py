"""Робот edu, 12.11 (одиннадцатый запуск): выдачи Яндекс Карт по районам → auto/fetch-queue.txt (ключи eu<N>-1121e).
На район: 2 запроса «Особым детям» + 2 по новым направлениям (сады, чтение, математика, ментальная арифметика, программирование, лего)."""
import json, os, urllib.parse
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
AREAS = ["Лесопарковая", "Лухмановская", "Мякинино", "Новаторская", "Окружная", "Нагатинский затон", "Озёрная", "Новоясеневская",
         "Народное Ополчение", "Мичуринский проспект", "Нижегородская", "Воскресенск", "Ступино", "Истра", "Дубна"]
TOWNS = {"Воскресенск", "Ступино", "Истра", "Дубна"}
INC = ["занятия для детей с ОВЗ", "инклюзивный центр для детей", "адаптивная физкультура для детей",
       "занятия для детей с аутизмом", "сенсорная интеграция для детей", "коррекционный центр для детей"]
TH = ["частный детский сад", "скорочтение для детей", "математический кружок для детей", "ментальная арифметика",
      "программирование для детей", "лего конструирование для детей", "обучение чтению детей", "школа программирования для детей"]
Q = []
for i, a in enumerate(AREAS):
    for t in (INC[(2 * i) % 6], INC[(2 * i + 1) % 6], TH[(2 * i) % 8], TH[(2 * i + 1) % 8]):
        Q.append(f"{t} {a}" if a in TOWNS else f"{t} метро {a}")
Q += ["адаптивное плавание для детей Москва", "иппотерапия для детей Москва", "инклюзивная студия для детей Москва",
      "центр для детей с синдромом Дауна Москва", "занятия для слабослышащих детей Москва", "сенсорная комната для детей Подмосковье"]
if __name__ == "__main__":
    urls = [f"https://yandex.ru/maps/1/moscow-and-moscow-oblast/?eu{n}=1121e&text=" + urllib.parse.quote(q) for n, q in enumerate(Q)]
    old = open(os.path.join(ROOT, "auto/fetch-queue.txt")).read()
    open(os.path.join(ROOT, "auto/fetch-queue.txt"), "w").write("\n".join(urls) + "\n" + old)
    json.dump(Q, open(os.path.join(ROOT, "tools/edu_1121_queries.json"), "w"), ensure_ascii=False, indent=0)
    print(len(urls))
