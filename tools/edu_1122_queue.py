"""Робот edu, 12.11 (двенадцатый запуск): выдачи Яндекс Карт по районам → auto/fetch-queue.txt (ключи eu<N>-1122e).
На район: 2 запроса «Особым детям» + 2 по новым направлениям (сады, чтение, математика, ментальная арифметика, программирование, лего)."""
import json, os, urllib.parse
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
AREAS = ["Локомотив", "Марксистская", "Нахимовский проспект", "Новокузнецкая", "Новослободская", "Новохохловская", "Окская",
         "Октябрьское поле", "Орехово", "Павелецкая", "Панфиловская", "Парк Победы", "Партизанская", "Первомайская", "Перово"]
INC = ["занятия для детей с ОВЗ", "инклюзивный центр для детей", "адаптивная физкультура для детей",
       "занятия для детей с аутизмом", "сенсорная интеграция для детей", "коррекционный центр для детей"]
TH = ["частный детский сад", "скорочтение для детей", "математический кружок для детей", "ментальная арифметика",
      "программирование для детей", "лего конструирование для детей", "обучение чтению детей", "школа программирования для детей"]
Q = []
for i, a in enumerate(AREAS):
    for t in (INC[(2 * i + 1) % 6], INC[(2 * i + 2) % 6], TH[(2 * i + 3) % 8], TH[(2 * i + 4) % 8]):
        Q.append(f"{t} метро {a}")
Q += ["иппотерапия для детей Подмосковье", "адаптивное плавание для детей Подмосковье", "инклюзивная театральная студия Москва",
      "занятия для детей с ДЦП Москва", "сенсорная комната для детей Москва", "занятия для слабовидящих детей Москва",
      "инклюзивный центр для детей Подольск", "инклюзивный центр для детей Балашиха", "занятия для детей с аутизмом Мытищи"]
if __name__ == "__main__":
    urls = [f"https://yandex.ru/maps/1/moscow-and-moscow-oblast/?eu{n}=1122e&text=" + urllib.parse.quote(q) for n, q in enumerate(Q)]
    old = open(os.path.join(ROOT, "auto/fetch-queue.txt")).read()
    open(os.path.join(ROOT, "auto/fetch-queue.txt"), "w").write("\n".join(urls) + "\n" + old)
    json.dump(Q, open(os.path.join(ROOT, "tools/edu_1122_queries.json"), "w"), ensure_ascii=False, indent=0)
    print(len(urls))
