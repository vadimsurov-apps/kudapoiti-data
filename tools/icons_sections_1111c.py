def poly(pts, c, sw=2.6):
    return f'<polygon points="{" ".join(f"{x:.1f},{y:.1f}" for x, y in pts)}" fill="{c}" {s(f"stroke-width=\"{sw}\"")}/>'


def add(pid, pal, body, hero, scene):
    k = f"zj_{pid}"
    draw_icons.BG[k] = pal
    ICONS[pid] = svg(k, body)
    SUBJ[pid] = f"{pid} — герой: {hero} | сцена: {scene}"


def ring(cx, cy, rx, ry, c, w):
    return f'<ellipse cx="{cx}" cy="{cy}" rx="{rx}" ry="{ry}" fill="none" stroke="{c}" stroke-width="{w}"/>'


def raw(d, c, w):
    return f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}" stroke-linecap="round"/>'


def star(cx, cy, r, c, sw=2.6, n=5, inner=0.45, rot=-90):
    pts = []
    for i in range(n * 2):
        rr = r if i % 2 == 0 else r * inner
        a = math.radians(rot + 180 / n * i)
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return poly(pts, c, sw)


