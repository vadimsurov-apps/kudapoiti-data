"""Робот edu, 13.11 (семнадцатый запуск): выдачи Яндекс Карт по районам → auto/fetch-queue.txt (ключи eu<N>-1127e).
На район: 2 запроса «Особым детям» + 2 по направлениям (сады, чтение, математика, ментальная арифметика, программирование, лего,
логопед, нейропсихолог, монтессори)."""
import json, os, urllib.parse
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
AREAS = ["Фонвизинская", "Фрунзенская", "Хорошёвская", "ЦСКА", "Царицыно", "Цветной бульвар", "Черкизовская", "Чертановская",
         "Чеховская", "Чистые пруды", "Чкаловская", "Шаболовская", "Шелепиха", "Шипиловская", "Шоссе Энтузиастов"]
INC = ["занятия для детей с ОВЗ", "инклюзивный центр для детей", "адаптивная физкультура для детей",
       "занятия для детей с аутизмом", "сенсорная интеграция для детей", "коррекционный центр для детей", "АВА-терапия для детей"]
TH = ["частный детский сад", "скорочтение для детей", "математический кружок для детей", "ментальная арифметика",
      "программирование для детей", "лего конструирование для детей", "логопед для детей", "нейропсихолог для детей", "монтессори"]
Q = []
for i, a in enumerate(AREAS):
    for t in (INC[(2 * i) % 7], INC[(2 * i + 1) % 7], TH[(2 * i) % 9], TH[(2 * i + 1) % 9]):
        Q.append(f"{t} метро {a}")
Q += ["инклюзивный центр для детей Звенигород", "занятия для детей с ОВЗ Нахабино", "адаптивная физкультура для детей Красногорск",
      "иппотерапия для детей Московская область", "инклюзивная театральная студия для детей Москва", "адаптивное плавание для детей Москва",
      "занятия для детей с синдромом Дауна Москва", "занятия для слабовидящих детей Москва", "частный детский сад Апрелевка",
      "программирование для детей Голицыно", "логопед для детей Кубинка", "инклюзивный центр для детей Электроугли"]
if __name__ == "__main__":
    urls = [f"https://yandex.ru/maps/1/moscow-and-moscow-oblast/?eu{n}=1127e&text=" + urllib.parse.quote(q) for n, q in enumerate(Q)]
    old = open(os.path.join(ROOT, "auto/fetch-queue.txt")).read()
    open(os.path.join(ROOT, "auto/fetch-queue.txt"), "w").write("\n".join(urls) + "\n" + old)
    json.dump(Q, open(os.path.join(ROOT, "tools/edu_1127_queries.json"), "w"), ensure_ascii=False, indent=0)
    print(len(urls))
