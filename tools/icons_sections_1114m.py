def flagline(y, cols):
    out = line(f"M-4 {y} Q64 {y+14} 132 {y}", O, 2)
    n = len(cols)
    for i, c in enumerate(cols):
        x = 6 + i * (120 / (n - 1))
        yy = y + 14 * (1 - ((x - 64) / 68) ** 2) - 1
        out += poly([(x - 6, yy), (x + 6, yy), (x, yy + 12)], c, 1.8)
    return out


