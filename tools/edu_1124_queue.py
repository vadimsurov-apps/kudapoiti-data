"""Робот edu, 13.11 (четырнадцатый запуск): выдачи Яндекс Карт по районам → auto/fetch-queue.txt (ключи eu<N>-1124e).
На район: 3 запроса «Особым детям» (их меньше всего) + 1 по новым направлениям (сады, чтение, математика, ментальная арифметика, программирование, лего)."""
import json, os, urllib.parse
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
AREAS = ["Речной вокзал", "Рижская", "Римская", "Ростокино", "Румянцево", "Рязанский проспект", "Савеловская", "Саларьево",
         "Свиблово", "Севастопольская", "Селигерская", "Семеновская", "Серпуховская", "Славянский бульвар", "Смоленская"]
INC = ["занятия для детей с ОВЗ", "инклюзивный центр для детей", "адаптивная физкультура для детей",
       "занятия для детей с аутизмом", "сенсорная интеграция для детей", "коррекционный центр для детей", "АВА-терапия для детей"]
TH = ["частный детский сад", "скорочтение для детей", "математический кружок для детей", "ментальная арифметика",
      "программирование для детей", "лего конструирование для детей", "обучение чтению детей", "школа программирования для детей"]
Q = []
for i, a in enumerate(AREAS):
    for t in (INC[(3 * i) % 7], INC[(3 * i + 1) % 7], INC[(3 * i + 2) % 7], TH[i % 8]):
        Q.append(f"{t} метро {a}")
Q += ["адаптивный спорт для детей Москва", "инклюзивный театр для детей Москва", "занятия для детей с ДЦП Москва",
      "инклюзивная студия для детей Москва", "иппотерапия для детей Подмосковье", "адаптивное плавание для детей Подмосковье",
      "инклюзивный центр для детей Мытищи", "инклюзивный центр для детей Балашиха", "инклюзивный центр для детей Одинцово",
      "занятия для детей с аутизмом Подольск", "занятия для детей с синдромом Дауна Подмосковье", "занятия для слабовидящих детей Москва"]
if __name__ == "__main__":
    urls = [f"https://yandex.ru/maps/1/moscow-and-moscow-oblast/?eu{n}=1124e&text=" + urllib.parse.quote(q) for n, q in enumerate(Q)]
    old = open(os.path.join(ROOT, "auto/fetch-queue.txt")).read()
    open(os.path.join(ROOT, "auto/fetch-queue.txt"), "w").write("\n".join(urls) + "\n" + old)
    json.dump(Q, open(os.path.join(ROOT, "tools/edu_1124_queries.json"), "w"), ensure_ascii=False, indent=0)
    print(len(urls))
