def add(pid, osm, name, typ, cats, tags, addr, a0, a1, d0, d1, energy, price, note, hours, plus, minus,
        indoor="да", adult=2, booking="желательна", adult_price=None, sit="нет", dark="нет", loud="нет",
        food="нет", season=None, site=None, src=SRCN, stroller="частично", crowd="частично"):
    c = CAND[osm]
    r = P(pid, name, typ, metro(c["lat"], c["lon"]), addr, c["lat"], c["lon"], a0, a1, d0, d1, energy, tags, price,
          note, hours, indoor, plus, minus, adult=adult, src=src, acc="точно (OpenStreetMap)",
          adult_price=adult_price, booking=booking, sit=sit, dark=dark, loud=loud, food=food, season=season,
          stroller=stroller, crowd=crowd)
    r["Сайт"] = site if site is not None else c.get("url")
    r["Категории"] = cats
    r["Проверено (дата)"] = "2026-11-06"
    ROWS.append(r)


