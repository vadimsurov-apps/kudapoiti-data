def line(d, c=O, w=3):
    return f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>'


def kidhead(x, y, r, hair, style="short", k=0.55):
    g = circ(0, 0, r, SKIN, 2.6)
    if style == "short":
        g += path(f"M{-r} -1 Q{-r} {-r-4} 0 {-r-3} Q{r} {-r-4} {r} -1 Q{r*0.4} {-r*0.55} 0 {-r*0.6} Q{-r*0.5} {-r*0.55} {-r} -1Z", hair, 2.2)
    elif style == "bun":
        g += circ(0, -r - 3, r * 0.45, hair, 2.2)
        g += path(f"M{-r} -1 Q{-r} {-r-3} 0 {-r-2} Q{r} {-r-3} {r} -1 Q{r*0.4} {-r*0.5} 0 {-r*0.55} Q{-r*0.5} {-r*0.5} {-r} -1Z", hair, 2.2)
    elif style == "tails":
        g += circ(-r - 2, -2, r * 0.42, hair, 2.2) + circ(r + 2, -2, r * 0.42, hair, 2.2)
        g += path(f"M{-r} -1 Q{-r} {-r-3} 0 {-r-2} Q{r} {-r-3} {r} -1 Q{r*0.4} {-r*0.5} 0 {-r*0.55} Q{-r*0.5} {-r*0.5} {-r} -1Z", hair, 2.2)
    g += face(0, 2, d=r * 0.38, k=k)
    return G(x, y, g)


