def line(d, c=O, w=3):
    return f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>'


def hair(c="#5D4037", r=12):
    return path(f"M{-r} -1 Q{-r} {-r-4} 0 {-r-3} Q{r} {-r-4} {r} -1 Q{r*0.4} {-r*0.55} 0 {-r*0.6} Q{-r*0.5} {-r*0.55} {-r} -1Z", c, 2.2)


def kid(x, y, r=11, hc="#5D4037", k=0.42, tails=False, extra=""):
    g = circ(0, 0, r, SKIN, 2.6) + hair(hc, r)
    if tails:
        g += path(f"M{-r} -4 Q{-r-10} 0 {-r-6} 10 Q{-r-2} 4 {-r+1} 2Z", hc, 2) + path(f"M{r} -4 Q{r+10} 0 {r+6} 10 Q{r+2} 4 {r-1} 2Z", hc, 2)
    return G(x, y, g + face(0, 2, d=r * 0.38, k=k) + extra)


def grass(y=100, c="#7CCB5B"):
    return path(f"M-6 {y} Q64 {y-6} 134 {y} V140 H-6Z", c, 2.6)


def star(x, y, r, c=GOLD, sw=2.2):
    pts = []
    for i in range(10):
        rr = r if i % 2 == 0 else r * 0.45
        a = -math.pi / 2 + i * math.pi / 5
        pts.append(f"{x + rr * math.cos(a):.1f} {y + rr * math.sin(a):.1f}")
    return path("M" + " L".join(pts) + "Z", c, sw)


def glove(c, k=1.0, fc=True):
    g = (path("M-14 -6 Q-16 -22 0 -22 Q16 -22 15 -4 Q15 10 4 14 L-10 14 Q-16 8 -14 -6Z", c, 2.8)
         + path("M-14 -2 Q-24 -4 -22 6 Q-20 12 -12 8", c, 2.6) + rect(-12, 12, 18, 10, WH, 2, 2.4))
    if fc:
        g += face(0, -6, d=5.5, k=0.55)
    return f'<g transform="scale({k})">{g}</g>'


