"""Робот edu, 13.11 (пятнадцатый запуск): выдачи Яндекс Карт по районам → auto/fetch-queue.txt (ключи eu<N>-1125e).
На район: 2 запроса «Особым детям» + 2 по новым направлениям (сады, чтение, математика, ментальная арифметика, программирование, лего)."""
import json, os, urllib.parse
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
AREAS = ["Театральная", "Текстильщики", "Телецентр", "Теплый Стан", "Терехово", "Технопарк", "Тимирязевская", "Третьяковская",
         "Тропарево", "Трубная", "Тульская", "Тургеневская", "Тушинская", "Тютчевская", "Угрешская"]
INC = ["занятия для детей с ОВЗ", "инклюзивный центр для детей", "адаптивная физкультура для детей",
       "занятия для детей с аутизмом", "сенсорная интеграция для детей", "коррекционный центр для детей", "АВА-терапия для детей"]
TH = ["частный детский сад", "скорочтение для детей", "математика для детей", "ментальная арифметика",
      "программирование для детей", "лего конструирование для детей", "обучение чтению детей", "монтессори центр"]
Q = []
for i, a in enumerate(AREAS):
    for t in (INC[(2 * i) % 7], INC[(2 * i + 1) % 7], TH[(2 * i) % 8], TH[(2 * i + 1) % 8]):
        Q.append(f"{t} метро {a}")
Q += ["инклюзивный центр для детей Химки", "инклюзивный центр для детей Королёв", "занятия для детей с ОВЗ Люберцы",
      "занятия для детей с ОВЗ Красногорск", "адаптивная физкультура для детей Зеленоград", "иппотерапия для детей Москва",
      "инклюзивная танцевальная студия для детей Москва", "занятия для детей с синдромом Дауна Москва", "адаптивное плавание для детей Москва",
      "логопед дефектолог для детей Видное", "занятия для детей с аутизмом Щёлково", "инклюзивная театральная студия Москва"]
if __name__ == "__main__":
    urls = [f"https://yandex.ru/maps/1/moscow-and-moscow-oblast/?eu{n}=1125e&text=" + urllib.parse.quote(q) for n, q in enumerate(Q)]
    old = open(os.path.join(ROOT, "auto/fetch-queue.txt")).read()
    open(os.path.join(ROOT, "auto/fetch-queue.txt"), "w").write("\n".join(urls) + "\n" + old)
    json.dump(Q, open(os.path.join(ROOT, "tools/edu_1125_queries.json"), "w"), ensure_ascii=False, indent=0)
    print(len(urls))
