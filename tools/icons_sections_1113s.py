def line(d, c=O, w=3):
    return f'<path d="{d}" fill="none" stroke="{c}" stroke-width="{w}" stroke-linecap="round" stroke-linejoin="round"/>'


def star(x, y, r, c="#FFC107", sw=2.2):
    pts = []
    for i in range(10):
        rr = r if i % 2 == 0 else r * 0.45
        a = -math.pi / 2 + i * math.pi / 5
        pts.append(f"{x + rr * math.cos(a):.1f} {y + rr * math.sin(a):.1f}")
    return path("M" + " L".join(pts) + "Z", c, sw)


def hair(c="#5D4037", r=12):
    return path(f"M{-r} -1 Q{-r} {-r-4} 0 {-r-3} Q{r} {-r-4} {r} -1 Q{r*0.4} {-r*0.55} 0 {-r*0.6} Q{-r*0.5} {-r*0.55} {-r} -1Z", c, 2.2)


def bun(c="#3E2723", r=11):
    return hair(c, r) + circ(0, -r - 4, 5, c, 2)


def fball(x, y, r, fc=True):
    """футбольный мяч: белый с чёрными пятиугольниками"""
    out = circ(x, y, r, WH, 3)
    p = []
    for i in range(5):
        a = -math.pi / 2 + i * 2 * math.pi / 5
        p.append(f"{x + r*0.36*math.cos(a):.1f} {y + r*0.36*math.sin(a):.1f}")
    out += path("M" + " L".join(p) + "Z", "#263238", 1.5)
    for i in range(5):
        a = -math.pi / 2 + i * 2 * math.pi / 5
        out += line(f"M{x + r*0.36*math.cos(a):.1f} {y + r*0.36*math.sin(a):.1f} L{x + r*0.86*math.cos(a):.1f} {y + r*0.86*math.sin(a):.1f}", "#263238", 1.6)
    if fc:
        out += face(x, y + r * 0.42, d=r * 0.3, k=r / 40, mouth=True)
    return out


