def star(cx, cy, r, c="#FFD54F", sw=2.4):
    import math
    pts = []
    for i in range(10):
        a = -math.pi / 2 + i * math.pi / 5
        rr = r if i % 2 == 0 else r * 0.45
        pts.append(f"{cx + rr * math.cos(a):.1f} {cy + rr * math.sin(a):.1f}")
    return f'<path d="M{" L".join(pts)}Z" fill="{c}" stroke="{O}" stroke-width="{sw}" stroke-linejoin="round"/>'


