"""Робот edu, 12.11 (десятый запуск): выдачи Яндекс Карт по районам → auto/fetch-queue.txt (ключи eu<N>-1120e).
По 2 запроса «Особым детям» + 2 по развитию/специалистам на район + общие запросы «Особым детям»."""
import json, os, urllib.parse
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
AREAS = ["Митино", "Мнёвники", "Молодежная", "Нагатинская", "Нагорная", "Некрасовка", "Новогиреево", "Новокосино",
         "Новопеределкино", "Новые Черемушки", "Отрадное", "Солнечногорск", "Фрязино", "Лыткарино", "Зеленоград"]
TOWNS = {"Солнечногорск", "Фрязино", "Лыткарино", "Зеленоград"}
INC = ["занятия для детей с ОВЗ", "инклюзивный центр для детей", "адаптивное плавание для детей",
       "занятия для детей с аутизмом", "АВА-терапия для детей", "сенсорная интеграция для детей"]
TH = ["монтессори", "центр раннего развития", "подготовка к школе", "английский для детей", "робототехника для детей",
      "детский логопед", "ЛФК для детей", "детский нейропсихолог"]
Q = []
for i, a in enumerate(AREAS):
    for t in (INC[(2 * i + 3) % 6], INC[(2 * i + 4) % 6], TH[(2 * i + 1) % 8], TH[(2 * i + 2) % 8]):
        Q.append(f"{t} {a}" if a in TOWNS else f"{t} метро {a}")
Q += ["иппотерапия для детей Подмосковье", "адаптивная физкультура для детей Москва", "инклюзивная театральная студия для детей Москва",
      "занятия для детей с синдромом Дауна Москва", "занятия для детей с ДЦП Москва", "сенсорная комната для детей Москва"]
if __name__ == "__main__":
    urls = [f"https://yandex.ru/maps/1/moscow-and-moscow-oblast/?eu{n}=1120e&text=" + urllib.parse.quote(q) for n, q in enumerate(Q)]
    old = open(os.path.join(ROOT, "auto/fetch-queue.txt")).read()
    open(os.path.join(ROOT, "auto/fetch-queue.txt"), "w").write("\n".join(urls) + "\n" + old)
    json.dump(Q, open(os.path.join(ROOT, "tools/edu_1120_queries.json"), "w"), ensure_ascii=False, indent=0)
    print(len(urls))
