"""Робот edu 14.11 (28-й запуск), волна 2 выдач: ещё 3 направления на каждый из 15 районов + «Особым детям» по городам Подмосковья (ключи eu<N>-1138g)."""
import json, os, urllib.parse
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
AREAS = ["метро Локомотив", "метро Лубянка", "метро Лужники", "метро Лухмановская", "метро Марксистская", "метро Менделеевская", "метро Минская",
         "метро Митино", "метро Мичуринский проспект", "Клин", "Егорьевск", "Наро-Фоминск", "Ивантеевка", "Дзержинский", "Солнечногорск"]
TH2 = ["лего студия для детей", "школа программирования для детей", "детский мини-сад", "обучение чтению дошкольников", "математика для детей",
       "ментальная арифметика для детей", "логопед дефектолог", "нейропсихолог для детей", "детский массаж ЛФК", "монтессори центр", "раннее развитие малышей",
       "английский для дошкольников", "робототехника", "подготовка к школе"]
Q3 = []
for i, a in enumerate(AREAS):
    for j in range(3): Q3.append(f"{TH2[(3 * i + j + 5) % len(TH2)]} {a}")
for d in ("Пушкино", "Сергиев Посад", "Раменское", "Жуковский", "Электросталь", "Ногинск", "Дмитров", "Чехов", "Серпухов", "Домодедово", "Реутов", "Долгопрудный"):
    Q3.append(f"занятия для детей с ОВЗ {d}")
if __name__ == "__main__":
    urls = [f"https://yandex.ru/maps/1/moscow-and-moscow-oblast/?eu{n}=1138g&text=" + urllib.parse.quote(q) for n, q in enumerate(Q3)]
    json.dump(Q3, open(os.path.join(ROOT, "tools/edu_1138_queries3.json"), "w"), ensure_ascii=False, indent=0)
    old = open(os.path.join(ROOT, "auto/fetch-queue.txt")).read()
    open(os.path.join(ROOT, "auto/fetch-queue.txt"), "w").write("\n".join(urls) + "\n" + old)
    print(len(urls))
